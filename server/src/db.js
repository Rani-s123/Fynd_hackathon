import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { DatabaseSync } = require('node:sqlite');

class Database extends DatabaseSync {
  pragma(str) {
    try {
      this.exec(`PRAGMA ${str}`);
    } catch (e) {
      // ignore in-memory pragma errors if any
    }
  }
}


const SCHEMA = `
CREATE TABLE IF NOT EXISTS stations (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  threshold INTEGER NOT NULL DEFAULT 3
);

CREATE TABLE IF NOT EXISTS products (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS defect_codes (
  code TEXT PRIMARY KEY,
  description TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS known_fixes (
  code TEXT PRIMARY KEY,
  title TEXT NOT NULL,
  probable_cause TEXT NOT NULL,
  documented_fix TEXT NOT NULL,
  safety_note TEXT NOT NULL,
  owner TEXT NOT NULL,
  last_reviewed TEXT NOT NULL,
  helpful_count INTEGER NOT NULL DEFAULT 0
);

-- Defect: raw event received from operator or inspection system (brief section 5)
CREATE TABLE IF NOT EXISTS defects (
  id TEXT PRIMARY KEY,
  station_id TEXT NOT NULL REFERENCES stations(id),
  product_id TEXT NOT NULL REFERENCES products(id),
  serial_number TEXT NOT NULL,
  defect_code TEXT NOT NULL,
  description TEXT NOT NULL,
  photo_data_url TEXT,
  occurred_at TEXT NOT NULL,
  logged_at TEXT NOT NULL,
  logged_by TEXT NOT NULL
);
-- Indexed for the pattern query per the brief's non-functional requirements (section 9).
CREATE INDEX IF NOT EXISTS idx_defects_pattern ON defects (station_id, defect_code, occurred_at);
CREATE INDEX IF NOT EXISTS idx_defects_dedup ON defects (station_id, serial_number, defect_code, logged_at);

-- Alert: operational signal generated by the rule engine (brief section 5)
CREATE TABLE IF NOT EXISTS alerts (
  id TEXT PRIMARY KEY,
  severity TEXT NOT NULL,
  station_id TEXT NOT NULL,
  defect_code TEXT NOT NULL,
  count INTEGER NOT NULL,
  threshold INTEGER NOT NULL,
  window_minutes INTEGER NOT NULL,
  first_occurrence TEXT NOT NULL,
  latest_occurrence TEXT NOT NULL,
  state TEXT NOT NULL,
  ticket_id TEXT,
  ncr_id TEXT,
  rule_version TEXT NOT NULL,
  recommended_action TEXT NOT NULL,
  containment TEXT DEFAULT '',
  corrective_action TEXT DEFAULT '',
  ncr_status TEXT DEFAULT 'DRAFT',
  created_at TEXT NOT NULL
);
-- One non-resolved alert per (station, defect_code) is the idempotency key (brief section 5.1 / 4.4).
CREATE INDEX IF NOT EXISTS idx_alerts_pattern ON alerts (station_id, defect_code, state);

CREATE TABLE IF NOT EXISTS tickets (
  id TEXT PRIMARY KEY,
  alert_id TEXT,
  defect_code TEXT NOT NULL,
  station_id TEXT NOT NULL,
  status TEXT NOT NULL,
  created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS ncrs (
  id TEXT PRIMARY KEY,
  alert_id TEXT NOT NULL,
  containment TEXT DEFAULT '',
  corrective_action TEXT DEFAULT '',
  status TEXT NOT NULL,
  created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS audit_events (
  id TEXT PRIMARY KEY,
  timestamp TEXT NOT NULL,
  actor TEXT NOT NULL,
  entity TEXT NOT NULL,
  action TEXT NOT NULL,
  details TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS alert_history (
  id TEXT PRIMARY KEY,
  alert_id TEXT NOT NULL,
  actor TEXT NOT NULL,
  from_state TEXT NOT NULL,
  to_state TEXT NOT NULL,
  note TEXT NOT NULL,
  timestamp TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS activity_events (
  id TEXT PRIMARY KEY,
  type TEXT NOT NULL,
  message TEXT NOT NULL,
  timestamp TEXT NOT NULL,
  actor TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

-- Persistent per-prefix counters so IDs (DEF-1001, ALT-2003, ...) survive server restarts.
CREATE TABLE IF NOT EXISTS id_seq (
  prefix TEXT PRIMARY KEY,
  value INTEGER NOT NULL
);
`;

function minutesAgo(m) {
  return new Date(Date.now() - m * 60_000).toISOString();
}
function hoursAgo(h) {
  return new Date(Date.now() - h * 3_600_000).toISOString();
}

