/**
 * @param {string} filePath - ':memory:' or a path to a .db file.
 * @param {{ seedReference?: boolean, seedHistory?: boolean }} [options]
 *   seedReference: stations/products/defect codes/known fixes/settings (default true).
 *   seedHistory: a small set of pre-existing demo defects/alerts so a fresh
 *     install isn't a completely blank screen (default true). Tests that want
 *     an exactly-known starting state pass `{ seedHistory: false }`.
 */
export function createDb(filePath, { seedReference = true, seedHistory = true } = {}) {
  const db = new Database(filePath);
  db.pragma('journal_mode = WAL');
  db.exec(SCHEMA);
  if (seedReference) seedReferenceData(db);
  if (seedHistory) seedDemoHistory(db);
  return db;
}

/** Persistent, per-prefix monotonic ID generator (DEF-1001, ALT-2003, ...). */
export function nextId(db, prefix) {
  const row = db.prepare('SELECT value FROM id_seq WHERE prefix = ?').get(prefix);
  const next = (row ? row.value : 0) + 1;
  if (row) {
    db.prepare('UPDATE id_seq SET value = ? WHERE prefix = ?').run(next, prefix);
  } else {
    db.prepare('INSERT INTO id_seq (prefix, value) VALUES (?, ?)').run(prefix, next);
  }
  return `${prefix}-${next}`;
}

export function getSetting(db, key, fallback) {
  const row = db.prepare('SELECT value FROM settings WHERE key = ?').get(key);
  return row ? row.value : fallback;
}

export function setSetting(db, key, value) {
  const existing = db.prepare('SELECT key FROM settings WHERE key = ?').get(key);
  if (existing) {
    db.prepare('UPDATE settings SET value = ? WHERE key = ?').run(value, key);
  } else {
    db.prepare('INSERT INTO settings (key, value) VALUES (?, ?)').run(key, value);
  }
}
